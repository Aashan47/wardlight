"""Regenerate the brief-13 constants table in docs/sources/engine.md from the registry.

    python -m engine.sources_doc

Rewrites only the block between the two markers below (appending it before "## Data" the first time). Day-and-month
dates are reduced to month and year, because the doc carries no calendar dates (tests/engine/test_constants.py).
"""

from __future__ import annotations

import re
from pathlib import Path

from . import constants as C

DOC = Path(__file__).resolve().parents[1] / "docs" / "sources" / "engine.md"
START = "<!-- brief13-constants:start (generated by python -m engine.sources_doc; do not edit by hand) -->"
END = "<!-- brief13-constants:end -->"
MONTHS = r"(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)[a-z]*"
NAMES = ("DIESEL_NGN_PER_L", "GEN_L_PER_KWH", "GEN_L_PER_KWH_MID", "GEN_OM_USD_PER_KWH", "GEN_LIFE_YEARS",
         "GENSET_15KVA_NGN", "GENSET_20KVA_NGN", "GENSET_30KVA_NGN", "GENSET_40KVA_NGN", "GENSET_50KVA_NGN",
         "GENSET_100KVA_NGN", "GENSET_POWER_FACTOR", "WATER_DENSITY_KG_M3", "STANDARD_GRAVITY_M_S2",
         "BH_PUMP_HEAD_M", "BH_PUMP_EFF", "BH_DEFAULT_HOURS", "PUMP_WINDOW_CENTRE_H", "SOLAR_BH_ARRAY_KWP_PER_KW",
         "WATER_WORKS_KW", "COLDHUB_PV_KWP", "COLDHUB_CAPEX_USD", "COLDHUB_FEE_NGN_PER_CRATE_DAY",
         "WATER_L_PER_PERSON_DAY", "MEPP_SUPPORT_NGN_PER_MONTH", "MEPP_CAPACITY_MW", "MEPP_AVG_DELIVERED_MW",
         "MEPP_COST_TARIFF_USC_PER_KWH", "MEPP_NBET_PAID_USC_PER_KWH", "ROOF_NEAREST_M", "ROOF_USABLE_FRACTION",
         "PV_KWP_PER_M2")


def undate(text: str) -> str:
    text = re.sub(r"\b\d{4}-\d{2}-\d{2}\b", "", text)
    return re.sub(rf"\b\d{{1,2}} ({MONTHS})\b", r"\1", text)


def _num(x: float) -> str:
    return f"{x:,.4f}".rstrip("0").rstrip(".") if abs(x) < 1000 else f"{x:,.0f}"


def table() -> str:
    rows = ["| Constant | Value (range) | Unit | Source | Status |", "|---|---|---|---|---|"]
    for n in NAMES:
        c = C.REGISTRY[n]
        v = _num(c.value) + (f" ({_num(c.lo)} to {_num(c.hi)})" if c.is_range and (c.lo, c.hi) != (c.value,) * 2
                             else "")
        src = undate(c.source + (f" Note: {c.note}" if c.note else "")).replace("|", "/")
        rows.append(f"| `{n}` | {v} | {c.unit} | {src} | {c.status} |")
    return "\n".join(rows)


def block() -> str:
    return "\n".join([
        START,
        "## Brief 13 constants (water, cold chain, generators, gas plant, roofs)",
        "",
        "Full quotes and grades: `docs/sources/brief13-sources.md`. The generator curve `GEN_L_PER_KWH` (clinic set) "
        "is used for health facilities in the batch and the outage scenario; `GEN_L_PER_KWH_MID` for boreholes, "
        "cold rooms and the water works (`engine/metrics13.py`).",
        "",
        table(),
        END,
    ])


def write(doc: Path = DOC) -> Path:
    text = doc.read_text()
    if START in text and END in text:
        a, rest = text.split(START, 1)
        _, b = rest.split(END, 1)
        text = a + block() + b
    else:
        text = text.replace("\n## Data\n", "\n" + block() + "\n\n## Data\n", 1)
    doc.write_text(text)
    return doc


if __name__ == "__main__":
    print(write())
